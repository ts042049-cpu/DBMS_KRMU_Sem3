CREATE TABLE INVENTORY_LOG (
    Log_ID       INT AUTO_INCREMENT PRIMARY KEY,
    Item_Code    VARCHAR(50) NOT NULL,
    Warehouse_ID VARCHAR(50) NOT NULL,
    Log_Time     DATETIME NOT NULL,
    Quantity     INT NOT NULL
);

