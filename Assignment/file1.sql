CREATE TABLE SPORTS_CLUB(
	Roll_No INT PRIMARY KEY,
    Student_Name VARCHAR(50),
    Year INT
);

CREATE TABLE MUSIC_CLUB (
    Roll_No INT PRIMARY KEY,
    Student_Name VARCHAR(50),
    Year INT
);

